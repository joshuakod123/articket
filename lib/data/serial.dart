/// 번호 규칙을 **한 군데**로 모은 곳.
///
/// ## 왜 따로 뺐나
///
/// 예전에는 번호를 만드는 자리가 세 군데로 흩어져 있었습니다.
///
/// 1. `mock_data.dart` — `AK-2026-00114` 처럼 **손으로 적은 문자열**
/// 2. `folder_screen.dart` — `AK-{올해}-{전체 티켓 수+1}`
/// 3. `profile_screen.dart` — `AK-{올해}-{전체 티켓 수}`
///
/// 그래서 이런 일이 벌어졌습니다.
///
/// * 2026년 첫 관람인데 번호는 `00114` (근거 없는 숫자)
/// * 회원증에는 "2025년부터"라고 쓰여 있는데 번호는 `AK-2026-…`
/// * 티켓 하나를 지우면 다음에 만든 티켓이 **앞 번호를 다시 씀**
/// * 회원 번호가 티켓을 추가할 때마다 조용히 바뀜 (회원 번호인데!)
///
/// 이제 번호는 저장하는 값이 아니라 **데이터에서 뽑아내는 값**입니다.
/// 티켓 목록이 바뀌면 [TicketStore]가 전체를 다시 매깁니다.
library;

/// 앱 전체가 쓰는 앞자리.
const kSerialPrefix = 'AK';

/// 티켓 발권 번호.
///
/// `AK-2026-014` = 2026년에 본 것 중 14번째.
///
/// 연도는 **관람한 해**입니다. 만든 날이 아닙니다. 2025년 전시를 올해
/// 뒤늦게 기록해도 번호는 `AK-2025-…` 가 되어야 자연스럽습니다.
String ticketSerial({required int year, required int seq}) =>
    '$kSerialPrefix-$year-${seq.toString().padLeft(3, '0')}';

/// 회원 번호.
///
/// 티켓 번호와 **일부러 다른 모양**으로 씁니다. 둘 다 `AK-2026-0006` 꼴이면
/// 프로필의 번호가 티켓 번호처럼 읽혀서, 사용자가 "이건 뭐지?" 하게 됩니다.
///
/// `M-2025-0006` = 2025년에 시작한 6번째 관람자.
String memberSerial({required int since, required int no}) =>
    'M-$since-${no.toString().padLeft(4, '0')}';