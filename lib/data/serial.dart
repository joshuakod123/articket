/// 번호 규칙을 **한 군데**로 모은 곳.
///
/// ## 지난번에 고친 것
///
/// 번호를 만드는 자리가 세 군데(mock · 서랍 화면 · 프로필)로 흩어져 있어서
/// 서로 다른 규칙이 동시에 돌아갔습니다. 그건 [TicketStore]로 모았습니다.
///
/// ## 이번에 고친 것 — 번호가 **다시 매겨지던** 문제
///
/// 그때는 번호를 "저장하는 값"이 아니라 "데이터에서 뽑아내는 값"으로 만들었습니다.
/// 목록이 바뀌면 전체를 다시 매겼습니다. 의도는 좋았지만 발권 번호로서는
/// 틀린 선택이었습니다.
///
/// * 3번 티켓을 버리면 **4번이 3번이 됩니다.** 공유 카드로 이미 내보낸
///   `AK-2026-004`가 세상 어디에도 없는 번호가 됩니다.
/// * 관람일을 하루 고치면 그날 이후 티켓의 번호가 **줄줄이 밀립니다.**
/// * 2025년 전시를 뒤늦게 기록하면 2025년 번호가 통째로 재배열됩니다.
///
/// 실물 티켓의 번호는 발권기가 찍는 순간 확정되고, 그 티켓을 버려도 그 번호는
/// 다시 쓰이지 않습니다. 이제 여기도 같습니다.
///
/// * 번호는 **티켓을 만들 때 한 번** 찍히고 그 뒤로 바뀌지 않습니다.
/// * 순번은 연도별 **최고값 + 1**입니다. 지운 번호를 되쓰지 않습니다.
/// * 연도는 **관람한 해**입니다. 관람일을 나중에 고쳐도 이미 찍힌 번호는
///   그대로 둡니다. (번호는 관람 기록이 아니라 발권 기록입니다)
///
/// 그래서 목록에 `AK-2026-003` 다음이 `AK-2026-005`인 구간이 생길 수 있습니다.
/// 그게 맞습니다. 표를 한 장 버린 티켓북은 원래 그렇게 생겼습니다.
library;

/// 앱 전체가 쓰는 앞자리.
const kSerialPrefix = 'AK';

/// 티켓 발권 번호.
///
/// `AK-2026-014` = 2026년에 발권한 14번째.
String ticketSerial({required int year, required int seq}) =>
    '$kSerialPrefix-$year-${seq.toString().padLeft(3, '0')}';

/// 아직 번호가 없는 티켓(초안)에 보여줄 자리표시.
const kUnissuedSerial = '$kSerialPrefix-0000-000';

/// 이미 찍힌 번호 문자열을 (연도, 순번)으로 되읽습니다.
///
/// 예전 버전이 문자열로만 저장해 둔 데이터를 이관할 때 씁니다.
/// 모양이 맞지 않으면 `null`을 돌려주고, 호출부가 새로 발권합니다.
({int year, int seq})? parseTicketSerial(String? raw) {
  if (raw == null) return null;
  final m = RegExp(r'^[A-Za-z]+-(\d{4})-(\d+)$').firstMatch(raw.trim());
  if (m == null) return null;
  final year = int.parse(m.group(1)!);
  final seq = int.parse(m.group(2)!);
  if (year < 1900 || seq < 1) return null;
  return (year: year, seq: seq);
}

/// 회원 번호.
///
/// 티켓 번호와 **일부러 다른 모양**으로 씁니다. 둘 다 `AK-2026-0006` 꼴이면
/// 프로필의 번호가 티켓 번호처럼 읽혀서, 사용자가 "이건 뭐지?" 하게 됩니다.
///
/// `M-2025-0006` = 2025년에 시작한 6번째 관람자.
String memberSerial({required int since, required int no}) =>
    'M-$since-${no.toString().padLeft(4, '0')}';